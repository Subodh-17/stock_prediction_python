"""
backtest.py
------------
A simple, transparent, look-ahead-bias-free backtest of the same BUY/SELL/
HOLD rule used live (trading/signal_generator.py) against historical
out-of-sample model predictions.

THIS MODULE DID NOT EXIST BEFORE -- there was no backtesting engine in the
project prior to this change. It is added fresh here (Phase 5), not audited
from a prior implementation.

--------------------------------------------------------------------------
TIMING / LOOK-AHEAD-BIAS ASSUMPTIONS (read before trusting any numbers)
--------------------------------------------------------------------------
For each day i (i >= 1) in the supplied date range:

  - `predicted_prices[i]` MUST be a prediction for day i's close that was
    produced using only information available up through day i-1 (this is
    exactly what data_loader.prepare_linear_regression_data /
    prepare_lstm_data's TEST split already gives you -- each test-set
    prediction comes from a model that never saw that row, or any later
    row, during training or scaling). This module does not re-verify that
    guarantee; it trusts the caller / pipeline to supply leakage-safe
    arrays, exactly as produced by the rest of this codebase after the
    Phase 1 data-leakage fix.
  - The trading signal for day i is generated by comparing
    `predicted_prices[i]` (tomorrow's forecast) against
    `actual_prices[i-1]` (today's already-known actual close) -- the exact
    same "% change vs current price" rule as trading/signal_generator.py,
    using the same buy/sell thresholds, so backtest signals are directly
    comparable to what the live pipeline would have signaled on that day.
  - The trade, if the rule fires, is assumed to FILL at `actual_prices[i]`
    (day i's own close). This is a standard simplifying assumption in
    lightweight daily backtests: you decide after seeing day i-1's close
    (all you have), and the next real execution opportunity is day i's
    session, approximated here by its close rather than modeling intraday
    price action or next-day open. It does not leak information into the
    *signal* (the signal never looks at actual_prices[i] or anything
    later) -- it only affects what price a trade is assumed to fill at.
  - Long-only: BUY opens/increases a position, SELL closes it entirely.
    No shorting, matching the rest of this project's trading model
    (trading/trade_executor.py has no short-sell path either).
  - Position sizing: a configurable fraction (`position_size_pct`, default
    1.0 = all available cash) is committed on each BUY; the whole position
    is liquidated on each SELL. This is deliberately simple/transparent
    rather than a more advanced sizing scheme, and can differ from the
    live MAX_POSITION_PCT risk cap used by trade_executor.py -- both are
    configurable, they are not required to match.
  - Transaction costs (`transaction_cost_pct`, applied each way) are
    deducted from every trade's notional value. No slippage model beyond
    that is applied (i.e., fills are assumed to happen exactly at the
    close price used, minus the transaction cost).
"""

from dataclasses import dataclass, field
from typing import List, Optional

import numpy as np
import pandas as pd

import config
import ensemble


@dataclass
class Trade:
    date: str
    action: str          # "BUY" or "SELL"
    price: float
    shares: float
    cost: float           # transaction cost paid on this trade
    pnl: Optional[float] = None          # only set on SELL (realized P&L for that round trip)
    cost_basis: Optional[float] = None   # only set on SELL: shares * entry_price for this round trip


@dataclass
class BacktestResult:
    strategy_name: str
    start_date: str
    end_date: str
    initial_capital: float
    final_portfolio_value: float
    total_return_pct: float
    annualized_return_pct: Optional[float]
    max_drawdown_pct: float
    sharpe_ratio: Optional[float]
    sortino_ratio: Optional[float]
    calmar_ratio: Optional[float]
    num_trades: int
    win_rate_pct: Optional[float]
    profit_factor: Optional[float]
    avg_trade_return_pct: Optional[float]
    total_transaction_costs: float
    buy_hold_return_pct: float
    open_position_at_end: bool
    trades: List[Trade] = field(default_factory=list)
    equity_curve: List[dict] = field(default_factory=list)  # [{date, portfolio_value}]
    assumptions: str = ""
    # Only meaningful for the "ensemble" backtest -- see
    # backtest_from_pipeline_result()'s `weighting_mode` parameter and
    # _compute_historical_dynamic_weights()'s docstring. "fixed" means the
    # same static config.ENSEMBLE_WEIGHTS split was applied uniformly
    # across the whole backtest period (valid either way -- a fixed
    # constant isn't derived from any data, so there's no leakage risk in
    # applying it uniformly to history). "dynamic" means a genuinely
    # historically-valid, day-by-day re-weighting was used, computed from
    # ONLY walk-forward folds that concluded strictly before each day.
    weighting_mode: str = "fixed"
    weighting_detail: Optional[dict] = None
    # The actual configuration this specific backtest ran with -- captured
    # explicitly rather than left implicit in config.py, since a caller can
    # override any of these per-call (see run_backtest's kwargs), and a
    # reproducibility record needs to reflect what ACTUALLY ran, not just
    # what the current global defaults happen to be.
    buy_threshold_pct: float = 0.0
    sell_threshold_pct: float = 0.0
    transaction_cost_pct: float = 0.0
    position_size_pct: float = 1.0
    # V17 additions (all defaulted so older constructors/serialized results keep working)
    execution: str = "close"
    slippage_bps: float = 0.0
    skipped_fills: int = 0
    exposure_pct: Optional[float] = None       # % of simulated days the strategy held a position at the close
    turnover_x: Optional[float] = None         # total traded value (buys + sells) / initial capital
    drawdown_curve: List[dict] = field(default_factory=list)      # [{date, drawdown_pct}]
    benchmark_curve: List[dict] = field(default_factory=list)     # Buy & Hold, same costs/entry rule
    signal_diagnostics: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        d = dict(vars(self))
        d["trades"] = [vars(t) for t in self.trades]
        return d

    def summary_text(self) -> str:
        lines = [
            f"Backtest: {self.strategy_name}  ({self.start_date} -> {self.end_date})",
            "--- TRADING STRATEGY PERFORMANCE (simulated, not model prediction error) ---",
        ]
        # weighting_detail is only ever set (non-None) for the "ensemble"
        # backtest (see backtest_from_pipeline_result) -- a single-model
        # (LR-only / LSTM-only) backtest doesn't blend anything, so there's
        # no weighting methodology to report at all; showing "Fixed
        # LR=35%/LSTM=45%/LLM=20%" next to a pure-LR backtest would be
        # misleading (none of that blending actually happened).
        if self.weighting_detail is not None:
            if self.weighting_mode == "dynamic":
                detail = self.weighting_detail or {}
                n_dynamic = detail.get("n_days_dynamic")
                n_fallback = detail.get("n_days_fixed_fallback")
                lines.append("  Backtest weighting:   Dynamic walk-forward")
                lines.append("                        Weights recalculated per day using only "
                             "walk-forward folds that concluded strictly before that day.")
                if n_dynamic is not None:
                    lines.append(f"                        {n_dynamic} day(s) dynamic, "
                                 f"{n_fallback} day(s) fixed fallback (not enough prior fold "
                                 f"history yet)")
            else:
                w = config.ENSEMBLE_WEIGHTS
                lines.append("  Backtest weighting:   Fixed")
                lines.append(f"                        LR = {w['linear_regression']:.0%}, "
                             f"LSTM = {w['lstm']:.0%}, LLM = {w['llm_panel']:.0%} "
                             f"(applied uniformly across the whole backtest period)")
        lines += [
            f"  Initial capital:      {self.initial_capital:,.2f}",
            f"  Final value:          {self.final_portfolio_value:,.2f}",
            f"  Total return:         {self.total_return_pct:+.2f}%",
            f"  Buy & Hold return:    {self.buy_hold_return_pct:+.2f}%  (baseline)",
        ]
        if self.annualized_return_pct is not None:
            lines.append(f"  Annualized return:    {self.annualized_return_pct:+.2f}%")
        lines.append(f"  Max drawdown:         {self.max_drawdown_pct:.2f}%")
        if self.sharpe_ratio is not None:
            lines.append(f"  Sharpe ratio:         {self.sharpe_ratio:.2f}")
        if self.sortino_ratio is not None:
            lines.append(f"  Sortino ratio:        {self.sortino_ratio:.2f}")
        if self.calmar_ratio is not None:
            lines.append(f"  Calmar ratio:         {self.calmar_ratio:.2f}")
        lines.append(f"  Number of trades:     {self.num_trades}")
        if self.win_rate_pct is not None:
            lines.append(f"  Win rate:             {self.win_rate_pct:.1f}%")
        if self.profit_factor is not None:
            lines.append(f"  Profit factor:        {self.profit_factor:.2f}")
        if getattr(self, "exposure_pct", None) is not None:
            lines.append(f"  Exposure:             {self.exposure_pct:.1f}% of days in the market")
        if getattr(self, "turnover_x", None) is not None:
            lines.append(f"  Turnover:             {self.turnover_x:.2f}x capital traded")
        if self.avg_trade_return_pct is not None:
            lines.append(f"  Avg trade return:     {self.avg_trade_return_pct:+.2f}%")
        lines.append(f"  Transaction costs:    {self.total_transaction_costs:,.2f}")
        if self.num_trades == 0 and getattr(self, "signal_diagnostics", {}).get("zero_trade_reason"):
            lines.append(f"  Zero-trade explanation: {self.signal_diagnostics['zero_trade_reason']}")
        if self.open_position_at_end:
            lines.append("  NOTE: a position was still open at the end of the backtest "
                          "period (marked to market at the final close).")
        return "\n".join(lines)


def run_backtest(dates, actual_prices, predicted_prices,
                  strategy_name: str = "model",
                  initial_capital: float = None,
                  transaction_cost_pct: float = None,
                  buy_threshold_pct: float = None,
                  sell_threshold_pct: float = None,
                  position_size_pct: float = 1.0,
                  weighting_mode: str = "fixed",
                  weighting_detail: dict = None,
                  open_prices=None, execution: str = "close",
                  slippage_bps: float = 0.0) -> BacktestResult:
    """
    Runs the backtest described in this module's docstring.

    dates, actual_prices, predicted_prices: equal-length, chronologically
    ordered sequences (index 0 = earliest). actual_prices[i] is the true
    close on dates[i]; predicted_prices[i] is the model's out-of-sample
    forecast for dates[i]'s close (see timing assumptions above).

    `execution` (V17):
      "close"      (default, backward compatible) fills at day i's close. The signal only uses data through
                   day i-1, so this is causally valid ONLY as a market-on-close order -- and optimistic.
      "next_open"  fills at day i's OPEN (requires `open_prices`): the first price tradable after a signal
                   computed from day i-1's close. A missing/invalid open means NO fill (never a guess).
    `slippage_bps`: adverse price impact applied to every fill (buys pay more, sells receive less).
    Positions are always marked to market at day i's close.

    `weighting_mode` / `weighting_detail`: purely descriptive metadata
    passed through to the returned BacktestResult, for the "ensemble"
    backtest to record which weighting methodology actually produced
    `predicted_prices` (see backtest_from_pipeline_result). Not used by
    single-model (LR-only / LSTM-only) backtests.
    """
    initial_capital = config.BACKTEST_INITIAL_CAPITAL if initial_capital is None else initial_capital
    if initial_capital <= 0:
        raise ValueError("initial_capital must be positive.")
    transaction_cost_pct = (config.BACKTEST_TRANSACTION_COST_PCT
                             if transaction_cost_pct is None else transaction_cost_pct)
    buy_threshold_pct = config.BUY_THRESHOLD_PCT if buy_threshold_pct is None else buy_threshold_pct
    sell_threshold_pct = config.SELL_THRESHOLD_PCT if sell_threshold_pct is None else sell_threshold_pct

    actual_prices = np.asarray(actual_prices, dtype=float)
    predicted_prices = np.asarray(predicted_prices, dtype=float)
    n = len(actual_prices)
    if n < 2 or len(predicted_prices) != n or len(dates) != n:
        raise ValueError("dates, actual_prices, and predicted_prices must be equal-length "
                          "sequences of at least 2 points.")
    if not np.all(np.isfinite(actual_prices)) or not np.all(actual_prices > 0):
        raise ValueError("actual_prices must all be finite and positive.")
    if not np.all(np.isfinite(predicted_prices)) or not np.all(predicted_prices > 0):
        raise ValueError("predicted_prices must all be finite and positive.")

    if execution not in ("close", "next_open"):
        raise ValueError("execution must be 'close' or 'next_open'.")
    if execution == "next_open":
        if open_prices is None or len(open_prices) != n:
            raise ValueError("execution='next_open' requires open_prices of the same length as the other series.")
        open_prices = np.asarray(open_prices, dtype=float)
    slip = slippage_bps / 10000.0
    if position_size_pct is not None and position_size_pct > 1.0:
        position_size_pct = position_size_pct / 100.0
    position_size_pct = max(0.01, min(1.0, float(position_size_pct or 1.0)))

    skipped_fills = 0
    entry_fee = 0.0
    days_long = 0
    traded_value = 0.0

    cash = initial_capital
    shares = 0.0
    entry_price = None
    trades: List[Trade] = []
    equity_curve = [{"date": str(dates[0]), "portfolio_value": initial_capital}]

    cost_frac = transaction_cost_pct / 100.0
    pct_changes: List[float] = []
    buy_signals = 0
    sell_signals = 0
    hold_signals = 0

    for i in range(1, n):
        yesterday_actual = actual_prices[i - 1]
        predicted_today = predicted_prices[i]
        pct_change = (predicted_today - yesterday_actual) / yesterday_actual * 100
        pct_changes.append(float(pct_change))

        if pct_change >= buy_threshold_pct:
            action = "BUY"
            buy_signals += 1
        elif pct_change <= sell_threshold_pct:
            action = "SELL"
            sell_signals += 1
        else:
            action = "HOLD"
            hold_signals += 1

        mark_price = actual_prices[i]
        if execution == "next_open":
            raw_fill = open_prices[i]
            if not (np.isfinite(raw_fill) and raw_fill > 0) and action in ("BUY", "SELL"):
                skipped_fills += 1
                action = "HOLD"
                raw_fill = mark_price
        else:
            raw_fill = mark_price
        fill_price = raw_fill * (1 + slip) if action == "BUY" else raw_fill * (1 - slip)

        if action == "BUY" and shares == 0:
            invest_amount = cash * position_size_pct
            cost = invest_amount * cost_frac
            net_invest = invest_amount - cost
            if net_invest > 0:
                new_shares = net_invest / fill_price
                cash -= invest_amount
                shares = new_shares
                entry_price = fill_price
                entry_fee = cost
                traded_value += invest_amount
                trades.append(Trade(date=str(dates[i]), action="BUY", price=fill_price,
                                     shares=new_shares, cost=cost))
        elif action == "SELL" and shares > 0:
            proceeds = shares * fill_price
            cost = proceeds * cost_frac
            net_proceeds = proceeds - cost
            cost_basis = shares * entry_price + entry_fee      # V20: the entry fee is part of what the position cost
            pnl = net_proceeds - cost_basis
            traded_value += proceeds
            cash += net_proceeds
            trades.append(Trade(date=str(dates[i]), action="SELL", price=fill_price,
                                 shares=shares, cost=cost, pnl=pnl, cost_basis=cost_basis))
            shares = 0.0
            entry_price = None
            entry_fee = 0.0
        # HOLD, or BUY-while-already-long, or SELL-while-flat: no action taken

        portfolio_value = cash + shares * mark_price
        days_long += 1 if shares > 0 else 0
        equity_curve.append({"date": str(dates[i]), "portfolio_value": float(portfolio_value)})

    final_value = equity_curve[-1]["portfolio_value"]
    open_position_at_end = shares > 0

    total_return_pct = (final_value / initial_capital - 1) * 100

    # Annualized return using calendar days spanned, if we have a real date range
    annualized_return_pct = None
    try:
        span_days = (_to_pydate(dates[-1]) - _to_pydate(dates[0])).days
        if span_days > 0:
            annualized_return_pct = ((final_value / initial_capital) ** (365.25 / span_days) - 1) * 100
    except Exception:
        # Best-effort only: a fractional power of a negative base (total loss,
        # final_value <= 0), an unexpected date type, or any other arithmetic
        # edge case leaves this None rather than crashing the whole backtest --
        # every other metric here is independent of it and still reported.
        pass

    values = np.array([e["portfolio_value"] for e in equity_curve])
    running_peak = np.maximum.accumulate(values)
    drawdowns = (values - running_peak) / running_peak
    max_drawdown_pct = float(drawdowns.min() * 100)

    daily_returns = np.diff(values) / values[:-1]
    sharpe_ratio = None
    if len(daily_returns) >= 2 and np.std(daily_returns) > 0:
        daily_rf = config.BACKTEST_RISK_FREE_RATE_ANNUAL_PCT / 100 / config.TRADING_DAYS_PER_YEAR
        sharpe_ratio = float((np.mean(daily_returns) - daily_rf) / np.std(daily_returns)
                              * np.sqrt(config.TRADING_DAYS_PER_YEAR))

    # Sortino ratio: like Sharpe, but only penalizes DOWNSIDE volatility
    # (the standard deviation of negative daily returns), since an
    # investor generally doesn't mind upside volatility -- only the risk of
    # loss. Undefined (None) when there are no negative daily returns at
    # all in the sample (nothing to divide by).
    sortino_ratio = None
    if len(daily_returns) >= 2:
        daily_rf = config.BACKTEST_RISK_FREE_RATE_ANNUAL_PCT / 100 / config.TRADING_DAYS_PER_YEAR
        downside_returns = daily_returns[daily_returns < 0]
        if len(downside_returns) > 0 and np.std(downside_returns) > 0:
            sortino_ratio = float((np.mean(daily_returns) - daily_rf) / np.std(downside_returns)
                                   * np.sqrt(config.TRADING_DAYS_PER_YEAR))

    # Calmar ratio: annualized return / max drawdown magnitude -- how much
    # return you got per unit of the worst peak-to-trough loss you'd have
    # had to sit through. Undefined when there was no drawdown at all
    # (division by ~0) or no annualized return could be computed.
    calmar_ratio = None
    if annualized_return_pct is not None and max_drawdown_pct < -1e-9:
        calmar_ratio = float(annualized_return_pct / abs(max_drawdown_pct))

    sell_trades = [t for t in trades if t.action == "SELL"]
    win_rate_pct = None
    profit_factor = None
    avg_trade_return_pct = None
    if sell_trades:
        wins = sum(1 for t in sell_trades if (t.pnl or 0) > 0)
        win_rate_pct = wins / len(sell_trades) * 100

        gross_profit = sum(t.pnl for t in sell_trades if (t.pnl or 0) > 0)
        gross_loss = sum(-t.pnl for t in sell_trades if (t.pnl or 0) < 0)
        # Profit factor = total winning $ / total losing $. Undefined (None)
        # when there were no losing trades at all (nothing to divide by) --
        # NOT reported as infinity, which would be misleading in a report.
        if gross_loss > 0:
            profit_factor = float(gross_profit / gross_loss)

        # Average return per closed round trip, as a % of that trade's own
        # cost basis -- lets you compare trade quality independent of
        # position size.
        trade_return_pcts = []
        for t in sell_trades:
            if t.cost_basis:
                trade_return_pcts.append((t.pnl / t.cost_basis) * 100)
        if trade_return_pcts:
            avg_trade_return_pct = float(np.mean(trade_return_pcts))

    total_costs = float(sum(t.cost for t in trades))

    # Buy & Hold baseline over the exact same period, same starting capital,
    # same one-way transaction cost applied at entry (and, symmetrically, at
    # the final exit so it's judged the same way a closed strategy would be).
    if execution == "next_open" and np.isfinite(open_prices[1]) and open_prices[1] > 0:
        bh_entry_idx, bh_entry_px = 1, open_prices[1] * (1 + slip)
    else:
        bh_entry_idx, bh_entry_px = 0, actual_prices[0]
    bh_shares = (initial_capital * (1 - cost_frac)) / bh_entry_px
    bh_final = bh_shares * actual_prices[-1] * (1 - cost_frac)
    buy_hold_return_pct = (bh_final / initial_capital - 1) * 100
    benchmark_curve = [{"date": str(dates[k]),
                        "portfolio_value": float(initial_capital if k < bh_entry_idx else bh_shares * actual_prices[k])}
                       for k in range(n)]
    drawdown_curve = [{"date": e["date"], "drawdown_pct": float(d * 100)} for e, d in zip(equity_curve, drawdowns)]

    pct_arr = np.array(pct_changes) if pct_changes else np.array([0.0])
    min_pct = float(np.min(pct_arr))
    max_pct = float(np.max(pct_arr))
    mean_pct = float(np.mean(pct_arr))
    std_pct = float(np.std(pct_arr)) if len(pct_arr) > 1 else 0.0

    zero_trade_reason = None
    if len(trades) == 0:
        if buy_signals == 0:
            zero_trade_reason = (
                f"The strategy stayed in 100% cash because no BUY signals were generated across {n - 1} out-of-sample days. "
                f"The model's predicted next-day % change ranged from {min_pct:+.2f}% to {max_pct:+.2f}% (mean {mean_pct:+.2f}%), "
                f"never reaching the Buy threshold (+{buy_threshold_pct:.2f}%)."
            )
        elif execution == "next_open" and skipped_fills > 0 and skipped_fills >= buy_signals:
            zero_trade_reason = (
                f"The strategy generated {buy_signals} BUY signal(s), but all {skipped_fills} fill(s) were skipped due to missing or non-positive open prices."
            )
        else:
            zero_trade_reason = "No trades were filled during the test window."

    signal_diagnostics = {
        "min_predicted_pct_change": min_pct,
        "max_predicted_pct_change": max_pct,
        "mean_predicted_pct_change": mean_pct,
        "std_predicted_pct_change": std_pct,
        "buy_signals": buy_signals,
        "sell_signals": sell_signals,
        "hold_signals": hold_signals,
        "buy_threshold_pct": float(buy_threshold_pct),
        "sell_threshold_pct": float(sell_threshold_pct),
        "zero_trade_reason": zero_trade_reason,
    }

    return BacktestResult(
        strategy_name=strategy_name,
        start_date=str(dates[0]),
        end_date=str(dates[-1]),
        initial_capital=float(initial_capital),
        final_portfolio_value=float(final_value),
        total_return_pct=float(total_return_pct),
        annualized_return_pct=annualized_return_pct,
        max_drawdown_pct=max_drawdown_pct,
        sharpe_ratio=sharpe_ratio,
        sortino_ratio=sortino_ratio,
        calmar_ratio=calmar_ratio,
        num_trades=len(trades),
        win_rate_pct=win_rate_pct,
        profit_factor=profit_factor,
        avg_trade_return_pct=avg_trade_return_pct,
        total_transaction_costs=total_costs,
        buy_hold_return_pct=float(buy_hold_return_pct),
        open_position_at_end=open_position_at_end,
        exposure_pct=float(days_long / len(equity_curve) * 100) if equity_curve else None,
        turnover_x=float(traded_value / initial_capital) if initial_capital else None,
        trades=trades,
        equity_curve=equity_curve,
        assumptions=(
            "Signal for day i compares a prediction for day i's close (made using only "
            "data through day i-1) against day i-1's actual close, using the same "
            "BUY/SELL/HOLD thresholds as live trading. "
            + ("Trades fill at day i's OPEN (first tradable price after the signal). "
               if execution == "next_open" else
               "Trades fill at day i's close (only achievable with a market-on-close order; optimistic). ")
            + f"Long-only, transaction cost {transaction_cost_pct:g}% each way, slippage {slippage_bps:g} bps. "
            "Positions are marked to market at each close. Prices are split/dividend adjusted. "
            "Simulated -- not a forecast of future returns. See backtest.py module docstring."
        ),
        weighting_mode=weighting_mode,
        weighting_detail=weighting_detail,
        buy_threshold_pct=float(buy_threshold_pct),
        sell_threshold_pct=float(sell_threshold_pct),
        transaction_cost_pct=float(transaction_cost_pct),
        position_size_pct=float(position_size_pct),
        execution=execution, slippage_bps=float(slippage_bps), skipped_fills=skipped_fills,
        drawdown_curve=drawdown_curve, benchmark_curve=benchmark_curve,
        signal_diagnostics=signal_diagnostics,
    )


def _to_pydate(d):
    """Best-effort conversion of a pandas Timestamp / str / datetime to a plain date."""
    if hasattr(d, "date"):
        return d.date()
    import datetime as _dt
    return _dt.datetime.fromisoformat(str(d)).date()


def _fixed_lr_lstm_split(llm_weight: float = None):
    """
    Returns (w_lr, w_lstm) from config.ENSEMBLE_WEIGHTS, renormalized so
    w_lr + w_lstm == 1 - llm_weight -- the same "LR/LSTM budget" convention
    ensemble._split_lr_lstm_budget uses for dynamic weights, so a "fixed"
    day and a "dynamic" day computed by _compute_historical_dynamic_weights
    below are on a directly comparable basis.
    """
    llm_weight = llm_weight if llm_weight is not None else config.ENSEMBLE_WEIGHTS["llm_panel"]
    weights = config.ENSEMBLE_WEIGHTS
    remaining = weights["linear_regression"] + weights["lstm"]
    raw_w_lr = weights["linear_regression"] / remaining if remaining > 0 else 0.5
    raw_w_lstm = weights["lstm"] / remaining if remaining > 0 else 0.5
    budget = 1.0 - llm_weight
    return raw_w_lr * budget, raw_w_lstm * budget


def _compute_historical_dynamic_weights(common_dates, wf_lr_dict, wf_lstm_dict,
                                         llm_weight: float = None,
                                         min_weight_floor: float = None,
                                         min_folds_required: int = None):
    """
    For each date in `common_dates`, computes a LEAKAGE-SAFE, historically
    valid LR/LSTM weight split using ONLY walk-forward folds whose test
    period concluded STRICTLY BEFORE that date.

    This is deliberately NOT "take today's final dynamic weights and apply
    them across the whole historical backtest" -- that would let each
    historical day's simulated trade be influenced by validation folds that
    hadn't happened yet as of that day, which is exactly the kind of
    future-information leak a backtest exists to avoid. Instead, each day's
    weight is recomputed from only the fold evidence that would genuinely
    have existed by that point in time.

    wf_lr_dict / wf_lstm_dict: dict form of a validation.WalkForwardResult
    (result["walk_forward_lr"] / result["walk_forward_lstm"] from a
    pipeline.run_pipeline() call made with walk_forward=True or
    ensemble_weighting_mode="dynamic"), i.e.
    {"folds": [{"test_end_date": "YYYY-MM-DD", "rmse": ...}, ...], ...}.

    For any date where fewer than `min_folds_required` PRIOR folds exist
    yet for either model (typically the earliest part of the backtest
    period, before enough walk-forward fold history has accumulated), that
    specific day falls back to the fixed config weights -- transparently,
    per day, mirroring the exact same fallback rule used for live
    predictions (ensemble.compute_dynamic_weights).

    Returns (weights_per_day, detail):
      weights_per_day: list of (w_lr, w_lstm) tuples, one per common_dates entry
      detail: {"n_days_dynamic": int, "n_days_fixed_fallback": int,
               "min_folds_required": int}
    """
    llm_weight = llm_weight if llm_weight is not None else config.ENSEMBLE_WEIGHTS["llm_panel"]
    min_weight_floor = (min_weight_floor if min_weight_floor is not None
                         else config.ENSEMBLE_MIN_WEIGHT_FLOOR)
    min_folds_required = (min_folds_required if min_folds_required is not None
                           else config.DYNAMIC_WEIGHTS_MIN_FOLDS)

    lr_folds = (wf_lr_dict or {}).get("folds") or []
    lstm_folds = (wf_lstm_dict or {}).get("folds") or []
    fixed_w_lr, fixed_w_lstm = _fixed_lr_lstm_split(llm_weight)

    weights_per_day = []
    n_dynamic = 0
    n_fallback = 0
    for d in common_dates:
        d_ts = pd.Timestamp(d)
        prior_lr = [f for f in lr_folds if pd.Timestamp(f["test_end_date"]) < d_ts]
        prior_lstm = [f for f in lstm_folds if pd.Timestamp(f["test_end_date"]) < d_ts]

        used_dynamic = False
        if len(prior_lr) >= min_folds_required and len(prior_lstm) >= min_folds_required:
            lr_rmse = float(np.mean([f["rmse"] for f in prior_lr]))
            lstm_rmse = float(np.mean([f["rmse"] for f in prior_lstm]))
            if np.isfinite(lr_rmse) and np.isfinite(lstm_rmse) and lr_rmse > 0 and lstm_rmse > 0:
                w_lr, w_lstm = ensemble._split_lr_lstm_budget(
                    lr_rmse, lstm_rmse, llm_weight, min_weight_floor
                )
                weights_per_day.append((w_lr, w_lstm))
                used_dynamic = True
                n_dynamic += 1
        if not used_dynamic:
            weights_per_day.append((fixed_w_lr, fixed_w_lstm))
            n_fallback += 1

    detail = {
        "n_days_dynamic": n_dynamic,
        "n_days_fixed_fallback": n_fallback,
        "min_folds_required": min_folds_required,
        "llm_weight": llm_weight,
        "min_weight_floor": min_weight_floor,
    }
    return weights_per_day, detail


def backtest_from_pipeline_result(result: dict, model: str = "lr",
                                   weighting_mode: str = "auto", **kwargs) -> BacktestResult:
    """
    Convenience wrapper: builds the (dates, actual_prices, predicted_prices)
    arrays from a pipeline.run_pipeline() result dict and runs the backtest.

    model: "lr", "lstm", or "ensemble" (LR+LSTM blended on their overlapping
    test dates -- the LLM panel is intentionally excluded from the
    backtest's predictions entirely, since there's no stored historical LLM
    prediction for each past test date to backtest against, only a live
    real-time opinion; its configured weight is still reserved out of the
    LR/LSTM budget below so the backtest's weighting stays on a consistent
    basis with the live ensemble -- it just never actually gets applied to
    a backtest prediction, the same as if the LLM panel were unavailable).

    `weighting_mode` (only affects model="ensemble"):
      - "auto" (default): matches whatever the LIVE prediction in `result`
        actually used. If result["final_ensemble"]["weights_used"]["mode"]
        is "dynamic", attempts a genuinely historically-valid, leakage-safe
        DAY-BY-DAY re-weighting (_compute_historical_dynamic_weights)
        using only walk-forward fold data that concluded strictly before
        each backtest day -- available only if `result` came from a run
        with walk_forward=True or ensemble_weighting_mode="dynamic". If the
        live run used "fixed" or "fixed_fallback" instead, the backtest
        uses that same fixed split uniformly across the whole period --
        which is NOT a leakage risk, since a static config constant isn't
        derived from any data, so applying it uniformly to history doesn't
        use anything a strategy "couldn't have known" at any point in time.
      - "fixed": force the fixed config.ENSEMBLE_WEIGHTS split regardless
        of what the live run used.
      - "dynamic": force the historical day-by-day re-weighting; raises
        ValueError if `result` has no walk-forward fold data to compute it
        from -- NEVER silently falls back to faking it with today's
        snapshot of dynamic weights applied across the whole backtest.

    See the returned BacktestResult.weighting_mode / weighting_detail for
    exactly which methodology was used and why (also included in
    BacktestResult.summary_text()).
    """
    if model == "lr":
        dates = list(result["lr_dates_test"])
        actual = np.asarray(result["y_test"], dtype=float)
        predicted = np.asarray(result["lr_eval"]["predictions"], dtype=float)
        return run_backtest(dates, actual, predicted, strategy_name="Linear Regression", **kwargs)

    if model == "lstm":
        dates = list(result["lstm_dates_test"])
        actual = np.asarray(result["lstm_eval"]["actual"], dtype=float)
        predicted = np.asarray(result["lstm_eval"]["predictions"], dtype=float)
        return run_backtest(dates, actual, predicted, strategy_name="LSTM", **kwargs)

    if model == "ensemble":
        lr_dates = list(result["lr_dates_test"])
        lstm_dates = list(result["lstm_dates_test"])
        lr_map = dict(zip((str(d) for d in lr_dates), zip(
            np.asarray(result["y_test"], dtype=float),
            np.asarray(result["lr_eval"]["predictions"], dtype=float),
        )))
        lstm_map = dict(zip((str(d) for d in lstm_dates), zip(
            np.asarray(result["lstm_eval"]["actual"], dtype=float),
            np.asarray(result["lstm_eval"]["predictions"], dtype=float),
        )))
        common_dates = sorted(set(lr_map) & set(lstm_map))
        if len(common_dates) < 2:
            raise ValueError("Not enough overlapping dates between LR and LSTM test sets "
                              "to build an ensemble backtest.")

        live_weights_used = (result.get("final_ensemble") or {}).get("weights_used") or {}
        live_mode = live_weights_used.get("mode", "fixed")
        # Correctly reflects 0% whenever the live run had no LLM panel
        # available (see the weights_used fix in ensemble.py) -- so this
        # naturally stays consistent with the live run's actual LLM
        # contribution, including the --skip-llm case used throughout this
        # project's own verification commands.
        llm_weight = live_weights_used.get("llm_panel", config.ENSEMBLE_WEIGHTS["llm_panel"])

        wf_lr_dict = result.get("walk_forward_lr")
        wf_lstm_dict = result.get("walk_forward_lstm")

        effective_mode = weighting_mode
        if effective_mode == "auto":
            effective_mode = "dynamic" if live_mode == "dynamic" else "fixed"
        elif effective_mode not in ("fixed", "dynamic"):
            raise ValueError(f"weighting_mode must be 'auto', 'fixed', or 'dynamic', got {weighting_mode!r}.")

        if effective_mode == "dynamic":
            if not wf_lr_dict or not wf_lstm_dict:
                raise ValueError(
                    "weighting_mode='dynamic' (or 'auto' with a live run that used dynamic "
                    "weighting) requires walk-forward fold data, but result['walk_forward_lr']/"
                    "['walk_forward_lstm'] is missing. Re-run the pipeline with walk_forward=True "
                    "(or ensemble_weighting_mode='dynamic') first -- this deliberately does NOT "
                    "fall back to faking dynamic weighting with a fixed split instead."
                )
            weights_per_day, weighting_detail = _compute_historical_dynamic_weights(
                common_dates, wf_lr_dict, wf_lstm_dict, llm_weight=llm_weight,
            )
            weighting_mode_used = "dynamic"
        else:
            fixed_w_lr, fixed_w_lstm = _fixed_lr_lstm_split(llm_weight)
            weights_per_day = [(fixed_w_lr, fixed_w_lstm)] * len(common_dates)
            weighting_mode_used = "fixed"
            weighting_detail = {
                "linear_regression": config.ENSEMBLE_WEIGHTS["linear_regression"],
                "lstm": config.ENSEMBLE_WEIGHTS["lstm"],
                "llm_panel": config.ENSEMBLE_WEIGHTS["llm_panel"],
            }

        actual, predicted = [], []
        for d, (w_lr, w_lstm) in zip(common_dates, weights_per_day):
            lr_actual, lr_pred = lr_map[d]
            lstm_actual, lstm_pred = lstm_map[d]
            # actual price should match between the two (same underlying series);
            # prefer the LR value (it doesn't go through scaler inverse-transform).
            actual.append(lr_actual)
            predicted.append(w_lr * lr_pred + w_lstm * lstm_pred)

        return run_backtest(common_dates, actual, predicted, strategy_name="LR+LSTM Ensemble",
                             weighting_mode=weighting_mode_used, weighting_detail=weighting_detail,
                             **kwargs)

    raise ValueError(f"Unknown model '{model}' -- expected 'lr', 'lstm', or 'ensemble'.")
